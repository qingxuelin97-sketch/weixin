describe('generated bytes land in the media library', () => {
  it('putGeneratedMedia writes a kind:"generated" row, registers it, returns an idb: ref', async () => {
    const blob = new Blob([new Uint8Array([1, 2, 3])], { type: 'image/png' });
    const ref = await putGeneratedMedia(blob, 'image/png', { now: 1_754_600_000_000, seed: 's1', tags: ['吃'] });
    expect(ref.startsWith('idb:gen_')).toBe(true);
    const id = ref.slice(4);
    expect(media.get(id)).toMatchObject({ kind: 'generated', tags: ['吃'], mime: 'image/png' });
    // Registered so the very next frame can draw it.
    expect(listRegisteredMedia('generated').some((m) => m.id === id)).toBe(true);
    // Deterministic id: same (now, seed) → same ref (rule #4, no Math.random).
    const ref2 = await putGeneratedMedia(blob, 'image/png', { now: 1_754_600_000_000, seed: 's1' });
    expect(ref2).toBe(ref);
  });

  it('generated items never enter the random photo pool', async () => {
    await putGeneratedMedia(new Blob(['x']), 'image/png', { now: 1, seed: 'a', tags: ['风景'] });
    expect(photoPoolIds()).toEqual([]);
    expect(photoPoolIds(['风景'], true)).toEqual([]);
  });

  it('generateToLibrary: not configured → null with zero network; failure → null, never a throw', async () => {
    const fetchSpy = vi.fn();
    globalThis.fetch = fetchSpy as unknown as typeof fetch;
    expect(await generateToLibrary({ prompt: 'x', tier: 'off', now: 1, seed: 's' })).toBeNull();
    expect(fetchSpy).not.toHaveBeenCalled();

    await saveImageProvider(CFG_SF);
    secrets.set(CFG_SF.keyAlias, 'k');
    globalThis.fetch = vi.fn(async () => {
      throw new Error('boom');
    }) as unknown as typeof fetch;
    expect(await generateToLibrary({ prompt: 'x', tier: 'off', now: 1, seed: 's' })).toBeNull();
  });

  it('generateToLibrary success: ref lands, tier gate still folded in', async () => {
    await saveImageProvider(CFG_SF);
    secrets.set(CFG_SF.keyAlias, 'k');
    globalThis.fetch = vi.fn(async () => okJson({ data: [{ b64_json: PNG_B64 }] })) as unknown as typeof fetch;
    const ref = await generateToLibrary({ prompt: 'x', tier: 'off', now: 2, seed: 's' });
    expect(ref?.startsWith('idb:gen_')).toBe(true);
    // full tier + mainland preset: silently null, zero calls.
    const spy = vi.fn();
    globalThis.fetch = spy as unknown as typeof fetch;
    expect(await generateToLibrary({ prompt: 'x', tier: 'full', now: 3, seed: 's' })).toBeNull();
    expect(spy).not.toHaveBeenCalled();
  });
});

