describe('AI 换头像（挂在 moment_post 尾部，无新 kind）', () => {
  const peer: ContactVM = { id: 'ai_a', type: 'ai', name: '林', avatarColor: '#000', avatarText: '林' };
  const persona = makePersona({ contactId: 'ai_a', core: '爱烘焙的邻家女孩' });

  function hooks() {
    const moments: MomentVM[] = [];
    const contacts: ContactVM[] = [];
    const h: MomentsHooks = {
      addMoment: async (m) => {
        moments.push(m);
      },
      applyLike: async () => {},
      addComment: async () => {},
      updateContact: async (c) => {
        contacts.push(c);
      },
      now: () => 1_754_600_000_000,
    };
    return { h, moments, contacts };
  }

  it('the gate is seeded and rare (deterministic, ~AVATAR_SWAP_RATE)', () => {
    expect(AVATAR_SWAP_RATE).toBeLessThanOrEqual(0.05);
    let hits = 0;
    for (let i = 0; i < 2000; i++) if (shouldSwapAvatar('ai_a', i * 97)) hits++;
    expect(hits / 2000).toBeGreaterThan(0.005);
    expect(hits / 2000).toBeLessThan(0.08);
    // Same inputs → same verdict, always.
    expect(shouldSwapAvatar('ai_a', 42)).toBe(shouldSwapAvatar('ai_a', 42));
  });

  it('swap: 512 avatar generated as kind "avatar", contact repointed, 换头像 moment posted', async () => {
    const stamp = [...Array(5000).keys()].map((i) => i * 131).find((t) => shouldSwapAvatar('ai_a', t));
    expect(stamp).toBeDefined();
    await saveImageProvider(CFG_SF);
    secrets.set(CFG_SF.keyAlias, 'k');
    let size = '';
    globalThis.fetch = vi.fn(async (_u: string, init: { body: string }) => {
      size = (JSON.parse(init.body) as { image_size: string }).image_size;
      return okJson({ data: [{ b64_json: PNG_B64 }] });
    }) as unknown as typeof fetch;

    const { h, moments, contacts } = hooks();
    await maybeAvatarSwap(persona, peer, [peer], () => persona, h, stamp!);

    expect(size).toBe('512x512');
    expect(contacts).toHaveLength(1);
    expect(contacts[0].avatarRef?.startsWith('idb:gen_')).toBe(true);
    const id = contacts[0].avatarRef!.slice(4);
    // kind 'avatar', NOT 'generated': hydration only eagerly materializes
    // avatars and eviction exempts them — any other kind degrades her face to
    // a placeholder tint after the next cold start.
    expect(media.get(id)).toMatchObject({ kind: 'avatar' });
    expect(moments).toHaveLength(1);
    expect(moments[0].text).toContain('换了个头像');
    expect(moments[0].imageRefs).toEqual([contacts[0].avatarRef]);
  });

  it('dice say no / no hook / not configured → nothing happens, silently', async () => {
    const stamp = [...Array(5000).keys()].map((i) => i * 131).find((t) => !shouldSwapAvatar('ai_a', t))!;
    const fetchSpy = vi.fn();
    globalThis.fetch = fetchSpy as unknown as typeof fetch;
    const a = hooks();
    await maybeAvatarSwap(persona, peer, [peer], () => persona, a.h, stamp);
    expect(a.moments).toHaveLength(0);

    // Dice yes but unconfigured: readiness gate answers first, zero network.
    const yes = [...Array(5000).keys()].map((i) => i * 131).find((t) => shouldSwapAvatar('ai_a', t))!;
    const b = hooks();
    await maybeAvatarSwap(persona, peer, [peer], () => persona, b.h, yes);
    expect(b.moments).toHaveLength(0);
    expect(b.contacts).toHaveLength(0);
    expect(fetchSpy).not.toHaveBeenCalled();
  });

  it('runMomentPost actually reaches the swap (写了没接线=没做)', () => {
    const src = readFileSync(resolve(__dirname, '../../src/ai/moments-service.ts'), 'utf8');
    const post = src.slice(src.indexOf('export async function runMomentPost'));
    expect(post.slice(0, post.indexOf('\n}'))).toContain('maybeAvatarSwap(');
  });
});

