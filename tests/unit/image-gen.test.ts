describe('generation transport', () => {
  it('unconfigured → typed error, zero network', async () => {
    const fetchSpy = vi.fn();
    globalThis.fetch = fetchSpy as unknown as typeof fetch;
    await expect(generateImage('x', 'off')).rejects.toMatchObject({ kind: 'not_configured' });
    expect(fetchSpy).not.toHaveBeenCalled();
  });

  it('siliconflow body speaks its native dialect (image_size/batch_size)', async () => {
    await saveImageProvider(CFG_SF);
    secrets.set(CFG_SF.keyAlias, 'k');
    let sent: Record<string, unknown> = {};
    globalThis.fetch = vi.fn(async (_u: string, init: { body: string }) => {
      sent = JSON.parse(init.body);
      return okJson({ images: [{ b64_json: PNG_B64 }] });
    }) as unknown as typeof fetch;
    await generateImage('一只猫', 'off', { size: '512x512' });
    expect(sent.image_size).toBe('512x512');
    expect(sent.batch_size).toBe(1);
    expect(sent.size).toBeUndefined();
  });

  it('openai/custom body speaks OpenAI (size/n/response_format), url hits /images/generations', async () => {
    await saveImageProvider(CFG_CUSTOM);
    secrets.set(CFG_CUSTOM.keyAlias, 'k');
    let url = '';
    let sent: Record<string, unknown> = {};
    globalThis.fetch = vi.fn(async (u: string, init: { body: string }) => {
      url = String(u);
      sent = JSON.parse(init.body);
      return okJson({ data: [{ b64_json: PNG_B64 }] });
    }) as unknown as typeof fetch;
    await generateImage('x', 'off');
    expect(url).toBe('https://gw.example.test/v1/images/generations');
    expect(sent.size).toBe('1024x1024');
    expect(sent.n).toBe(1);
    expect(sent.response_format).toBe('b64_json');
  });

  it('b64_json preferred; url-only answers are re-fetched into a blob', async () => {
    await saveImageProvider(CFG_SF);
    secrets.set(CFG_SF.keyAlias, 'k');
    const calls: string[] = [];
    globalThis.fetch = vi.fn(async (u: string) => {
      calls.push(String(u));
      if (String(u).includes('/images/generations')) {
        return okJson({ images: [{ url: 'https://cdn.example.test/out.png' }] });
      }
      return okJson({});
    }) as unknown as typeof fetch;
    const r = await generateImage('x', 'off');
    expect(calls).toHaveLength(2);
    expect(calls[1]).toBe('https://cdn.example.test/out.png');
    expect(r.mime).toBe('image/png');
    expect(r.blob.size).toBeGreaterThan(0);
  });

  it('auth/ratelimit/server statuses map to typed kinds', async () => {
    await saveImageProvider(CFG_SF);
    secrets.set(CFG_SF.keyAlias, 'k');
    for (const [status, kind] of [
      [401, 'auth'],
      [429, 'rate_limit'],
      [500, 'server'],
    ] as const) {
      globalThis.fetch = vi.fn(async () =>
        ({ ok: false, status, text: async () => '{}' }) as unknown as Response,
      ) as unknown as typeof fetch;
      await expect(generateImage('x', 'off')).rejects.toMatchObject({ kind });
    }
  });

  it('a hanging endpoint rejects with timeout around the deadline, never awaits forever', async () => {
    await saveImageProvider(CFG_SF);
    secrets.set(CFG_SF.keyAlias, 'k');
    globalThis.fetch = vi.fn(
      (_u: unknown, init?: { signal?: AbortSignal }) =>
        new Promise((_res, rej) => {
          init?.signal?.addEventListener('abort', () => rej(new Error('aborted')));
        }),
    ) as unknown as typeof fetch;
    const t0 = Date.now();
    await expect(generateImage('x', 'off', { timeoutMs: 120 })).rejects.toMatchObject({
      kind: 'timeout',
    });
    expect(Date.now() - t0).toBeLessThan(2_000);
  });

  it('url download rides the bridge fallback with a REJECTING deadline (constitution trap)', async () => {
    // fetch fails → bridge hangs → raceDeadline must reject, boundedly.
    (globalThis as { Capacitor?: unknown }).Capacitor = { isNativePlatform: () => true };
    globalThis.fetch = vi.fn(async () => {
      throw new Error('no cors');
    }) as unknown as typeof fetch;
    try {
      await expect(
        fetchImageBlob('https://cdn.example.test/out.png', 150),
      ).rejects.toMatchObject({ name: 'ImageGenError' });
      expect(bridgeRequest).toHaveBeenCalledTimes(1);
    } finally {
      delete (globalThis as { Capacitor?: unknown }).Capacitor;
    }
  });

  it('every generation is a counted paid call (usage kind "image")', async () => {
    await saveImageProvider(CFG_SF);
    secrets.set(CFG_SF.keyAlias, 'k');
    globalThis.fetch = vi.fn(async () => okJson({ data: [{ b64_json: PNG_B64 }] })) as unknown as typeof fetch;
    await generateImage('x', 'off');
    await new Promise((r) => setTimeout(r, 10)); // recordUsage is fire-and-forget
    const rows = settings.get('usage:daily') as Array<{ counts: Record<string, number> }>;
    expect(rows?.[0]?.counts.image).toBe(1);
  });
});

