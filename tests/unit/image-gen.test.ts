/**
 * M-J3 图片生成 — transport, tier gate, media landing, and wiring guards.
 *
 * image.ts is the SECOND module in the repo that talks to the network directly
 * (after llm/http), which is exactly why every guarantee here is a red-flip
 * test rather than a review note:
 *   1. unconfigured → typed error, ZERO network attempts;
 *   2. 铁律 6: a full-tier prompt never reaches a preset (SiliconFlow is a
 *      mainland official endpoint!) — only a user-declared capable custom one;
 *   3. b64 preferred, url re-fetched into a blob before the CDN link dies;
 *   4. generated bytes land as `kind: 'generated'` media rows, OUT of the
 *      random photo pool;
 *   5. every calling surface degrades to the old pool path on any failure;
 *   6. each generation is a counted paid call.
 */

